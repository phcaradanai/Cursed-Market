// Reproducible end-only DTOs; negative variant is a labelled presentation fixture, never runtime rules.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {replayAppraisalAudit} from '../dist/src/game/appraisal/audit.js';
import {appraisalViewFor} from '../dist/src/game/appraisal/views.js';
import {calculatePersonalScore} from '../dist/src/game/appraisal/personal-scoring.js';
import {previewRooms} from '../dist/src/appraisal-client/comic-preview-data.js';
const root=fileURLToPath(new URL('../../..',import.meta.url)),out={};
for(const [scene,file]of [['score-2','normal-personal/journey.audit.json'],['score-4','4-players.audit.json']]){
 const input=JSON.parse(fs.readFileSync(path.join(root,'docs/validation/personal-scoring-eligibility-2026-11-03',file))),state=replayAppraisalAudit(input.run??input);
 const game=appraisalViewFor(state,state.players[0].id),room=structuredClone(previewRooms.inspection);
 Object.assign(room,{game,yourSeatId:state.players[0].id,hostId:state.players[0].id,matchSeats:state.players.map((p,i)=>({id:p.id,name:i===0?'คุณ':`ผู้เล่น ${i+1}`}))});out[scene]=room;
 if(scene==='score-2'){
  const negative=structuredClone(room);
  negative.game.collector=state.collector.map(row=>{const items=row.items.map(i=>state.items[i.id]),score=calculatePersonalScore({playerId:row.playerId,facts:state.personalPerformance.facts,assetScore:row.credits+row.itemValue,modifierPercent:-20,ghostBonus:state.ghosts?.[row.playerId]?.bonus??0,rarities:items.filter(i=>!i.copy).map(i=>({id:i.id,rarity:i.appearance?.rarity??'common'}))});return {...row,modifierPercent:-20,personalScore:score,score:score.total};});
  out['score-neg']=negative;
 }
}
fs.writeFileSync(path.join(root,'apps/comic/src/appraisal-client/personal-score-preview-data.ts'),`// Generated by scripts/personal-score-preview.mjs from sealed end audits; score-neg is a presentation fixture.\nimport type {AppraisalRoomView} from '../shared/appraisal-protocol.js';\nexport const personalScorePreview=${JSON.stringify(out)} as unknown as Record<string,AppraisalRoomView>;\n`);
console.log('End-only score previews generated: score-2 / score-4 / score-neg');
