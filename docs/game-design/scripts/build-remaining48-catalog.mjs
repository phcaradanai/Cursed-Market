#!/usr/bin/env node
// Build-time approved contract data only; never load design files inside a live game.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const approval=JSON.parse(read('docs/game-design/remaining48-approval.json'));
const source=read(approval.proposal),spec=JSON.parse(source),hash=crypto.createHash('sha256').update(source).digest('hex');
assert.equal(approval.status,'approved-experimental');assert.equal(hash,approval.proposalSha256,'Approved spec changed');
assert.equal(execFileSync('git',['show',approval.proposalRevision+':'+approval.proposal],{cwd:root,encoding:'utf8'}),source,'Frozen approved revision changed');
assert.equal(spec.items.length,48);assert.equal(Object.keys(spec.effectContracts).length,35);
assert.deepEqual(spec.items.map(i=>i.id),approval.approvedItemIds);
assert.deepEqual(spec.meaningProposals.map(i=>i.id),approval.approvedMeaningIds);
const items=Object.fromEntries(spec.items.map(item=>{
 const rule=spec.effectContracts[item.contract];assert(rule&&item.optionalEffectsEnabled===false);
 return [item.id,{name:item.name,anchor:item.anchor,merchant:item.merchantId,family:item.type,nativeEffect:'effect:'+item.primaryEffect,mode:rule.mode,cost:rule.cost,consumable:rule.mode==='consume',explicitActivation:rule.mode!=='held'}];
}));
for(const merchant of new Set(spec.items.map(i=>i.merchantId)))assert.equal(spec.items.filter(i=>i.merchantId===merchant).length,6);
for(const [effect,rule]of Object.entries(spec.effectContracts)){
 assert(spec.items.some(i=>i.primaryEffect===effect));
 assert(['held','active','consume'].includes(rule.mode));assert.equal(rule.cost,rule.mode==='held'?0:1);
 for(const value of Object.values(rule.parameters))assert(typeof value==='boolean'||Number.isFinite(value)&&value>0);
}
const rules=Object.fromEntries(Object.entries(spec.effectContracts).map(([id,rule])=>[id,rule.parameters]));
const code=`// Generated by docs/game-design/scripts/build-remaining48-catalog.mjs from the frozen approved specification.\n// Contract data is not a runtime binding. Catalog selection stays unchanged until owner hooks are complete.\nexport const REMAINING48_SPEC_SHA = '${hash}';\nexport const REMAINING48_ITEMS = ${JSON.stringify(items,null,2)} as const;\nexport const REMAINING48_RULES = ${JSON.stringify(rules,null,2)} as const;\nexport type Remaining48Kind = keyof typeof REMAINING48_ITEMS;\nexport type Remaining48Effect = keyof typeof REMAINING48_RULES;\n`;
const target='apps/comic/src/game/appraisal/remaining48-catalog.ts';
if(process.argv.includes('--check'))assert.equal(read(target),code,'Generated runtime contract data stale');else fs.writeFileSync(path.join(root,target),code);
console.log('PASS: exact approved48 catalog contracts and35numeric rule groups; no runtime/default activation.');
